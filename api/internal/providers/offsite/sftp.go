// Package offsite implements the production off-site backup path: archives are
// built locally by the streaming local provider, uploaded over SFTP (a Hetzner
// Storage Box speaks SFTP/SSH on port 23), then hash-verified from the remote
// copy. Choice rationale (docs/BACKUPS.md): the Storage Box offers SFTP but no
// S3 API, SFTP needs no extra service on the host, and SSH host-key pinning is
// a simpler trust model than a TLS endpoint we do not control.
//
// Security properties:
//   - the server host key MUST match a pinned SHA256 fingerprint (no
//     known_hosts auto-add, no InsecureIgnoreHostKey);
//   - credentials come from files supplied by the operator, are held in memory
//     only for the connection, and never appear in errors, logs or audit data;
//   - remote object names are generated by Nodera and validated, never taken
//     from request input.
package offsite

import (
	"context"
	"errors"
	"fmt"
	"io"
	"net"
	"os"
	"path"
	"regexp"
	"strings"
	"time"

	"github.com/pkg/sftp"
	"golang.org/x/crypto/ssh"

	"github.com/nodera/nodera/internal/providers"
)

// Store is the remote object store the backup provider needs.
type Store interface {
	// Put writes r under name atomically (temp name + rename) and returns the size written.
	Put(ctx context.Context, name string, r io.Reader) (int64, error)
	Get(ctx context.Context, name string) (io.ReadCloser, error)
	Size(ctx context.Context, name string) (int64, error)
	Delete(ctx context.Context, name string) error
}

// SFTPConfig configures the store. Exactly one of PrivateKeyPEM / Password is set.
type SFTPConfig struct {
	Addr          string // host:port
	User          string
	Dir           string // remote directory; must exist
	PrivateKeyPEM []byte
	Password      string
	// HostKeySHA256 lists the accepted server host key fingerprints, each either
	// "SHA256:..." (any key type) or "ssh-ed25519 SHA256:..." (bound to a key
	// type, which also makes the client negotiate that type — a server offers
	// several host keys and the client would otherwise pick one you did not pin).
	// At least one is required.
	HostKeySHA256 []string
	DialTimeout   time.Duration
}

type SFTPStore struct{ cfg SFTPConfig }

// ErrHostKey is returned when the server presents a key that is not pinned.
var ErrHostKey = errors.New("sftp: server host key does not match the pinned fingerprint")

func NewSFTPStore(cfg SFTPConfig) (*SFTPStore, error) {
	if cfg.Addr == "" || cfg.User == "" || cfg.Dir == "" {
		return nil, errors.New("sftp: addr, user and dir are required")
	}
	if len(cfg.HostKeySHA256) == 0 {
		return nil, errors.New("sftp: a pinned host key fingerprint is required")
	}
	for _, f := range cfg.HostKeySHA256 {
		if _, _, err := parsePin(f); err != nil {
			return nil, err
		}
	}
	if (len(cfg.PrivateKeyPEM) == 0) == (cfg.Password == "") {
		return nil, errors.New("sftp: set exactly one of private key or password")
	}
	if cfg.DialTimeout == 0 {
		cfg.DialTimeout = 30 * time.Second
	}
	return &SFTPStore{cfg: cfg}, nil
}

func (s *SFTPStore) sshConfig() (*ssh.ClientConfig, error) {
	var auth ssh.AuthMethod
	if len(s.cfg.PrivateKeyPEM) > 0 {
		signer, err := ssh.ParsePrivateKey(s.cfg.PrivateKeyPEM)
		if err != nil {
			return nil, errors.New("sftp: the private key could not be parsed (passphrase-protected keys are not supported)")
		}
		auth = ssh.PublicKeys(signer)
	} else {
		auth = ssh.Password(s.cfg.Password)
	}
	pinned := map[string]struct{}{}
	var algs []string
	for _, f := range s.cfg.HostKeySHA256 {
		alg, fp, _ := parsePin(f) // validated in NewSFTPStore
		pinned[fp] = struct{}{}
		if alg != "" {
			algs = append(algs, alg)
		}
	}
	return &ssh.ClientConfig{
		HostKeyAlgorithms: algs, // empty = client default; pins bound to a type narrow it
		User:              s.cfg.User,
		Auth:              []ssh.AuthMethod{auth},
		HostKeyCallback: func(_ string, _ net.Addr, key ssh.PublicKey) error {
			got := ssh.FingerprintSHA256(key)
			if _, ok := pinned[got]; ok {
				return nil
			}
			// Only the presented fingerprint is reported: it is public information
			// the operator needs to compare, and nothing secret.
			return fmt.Errorf("%w (server presented %s)", ErrHostKey, got)
		},
		Timeout: s.cfg.DialTimeout,
	}, nil
}

// parsePin splits "[key-type ]SHA256:fingerprint".
func parsePin(pin string) (alg, fp string, err error) {
	f := strings.Fields(pin)
	switch len(f) {
	case 1:
		fp = f[0]
	case 2:
		alg, fp = f[0], f[1]
	}
	if !strings.HasPrefix(fp, "SHA256:") || len(fp) < 10 {
		return "", "", errors.New(`sftp: host key pins must look like "SHA256:<base64>" or "ssh-ed25519 SHA256:<base64>"`)
	}
	return alg, fp, nil
}

// session opens one SFTP connection. Cancelling ctx closes it, which unblocks
// any transfer in flight. The returned func releases everything.
func (s *SFTPStore) session(ctx context.Context) (*sftp.Client, func(), error) {
	cc, err := s.sshConfig()
	if err != nil {
		return nil, nil, err
	}
	d := net.Dialer{Timeout: s.cfg.DialTimeout}
	conn, err := d.DialContext(ctx, "tcp", s.cfg.Addr)
	if err != nil {
		return nil, nil, fmt.Errorf("sftp: connect: %w", err)
	}
	sc, chans, reqs, err := ssh.NewClientConn(conn, s.cfg.Addr, cc)
	if err != nil {
		conn.Close()
		return nil, nil, fmt.Errorf("sftp: handshake: %w", scrub(err))
	}
	client, err := sftp.NewClient(ssh.NewClient(sc, chans, reqs), sftp.MaxConcurrentRequestsPerFile(16))
	if err != nil {
		sc.Close()
		return nil, nil, fmt.Errorf("sftp: subsystem: %w", err)
	}
	stop := make(chan struct{})
	go func() {
		select {
		case <-ctx.Done():
			client.Close()
			sc.Close()
		case <-stop:
		}
	}()
	return client, func() { close(stop); client.Close(); sc.Close() }, nil
}

// scrub keeps authentication failures generic: the underlying message can echo
// details about the credential type that was offered.
func scrub(err error) error {
	if errors.Is(err, ErrHostKey) {
		return err
	}
	if strings.Contains(err.Error(), "unable to authenticate") {
		return errors.New("authentication failed")
	}
	return err
}

var nameRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,200}$`)

func (s *SFTPStore) remote(name string) (string, error) {
	if !nameRe.MatchString(name) || strings.Contains(name, "..") {
		return "", fmt.Errorf("sftp: invalid object name %q", name)
	}
	return path.Join(s.cfg.Dir, name), nil
}

type ctxReader struct {
	ctx context.Context
	r   io.Reader
}

func (c ctxReader) Read(p []byte) (int, error) {
	if err := c.ctx.Err(); err != nil {
		return 0, err
	}
	return c.r.Read(p)
}

func (s *SFTPStore) Put(ctx context.Context, name string, r io.Reader) (int64, error) {
	final, err := s.remote(name)
	if err != nil {
		return 0, err
	}
	c, done, err := s.session(ctx)
	if err != nil {
		return 0, err
	}
	defer done()
	tmp := final + ".part"
	f, err := c.OpenFile(tmp, os.O_WRONLY|os.O_CREATE|os.O_TRUNC)
	if err != nil {
		return 0, fmt.Errorf("sftp: create: %w", err)
	}
	n, err := io.Copy(f, ctxReader{ctx, r})
	if cerr := f.Close(); err == nil {
		err = cerr
	}
	if err != nil {
		_ = c.Remove(tmp)
		return 0, fmt.Errorf("sftp: upload: %w", err)
	}
	_ = c.Remove(final) // PosixRename is not universal; make room explicitly
	if err := c.Rename(tmp, final); err != nil {
		_ = c.Remove(tmp)
		return 0, fmt.Errorf("sftp: finalize: %w", err)
	}
	return n, nil
}

type remoteFile struct {
	io.ReadCloser
	done func()
}

func (r remoteFile) Close() error { err := r.ReadCloser.Close(); r.done(); return err }

func (s *SFTPStore) Get(ctx context.Context, name string) (io.ReadCloser, error) {
	p, err := s.remote(name)
	if err != nil {
		return nil, err
	}
	c, done, err := s.session(ctx)
	if err != nil {
		return nil, err
	}
	f, err := c.Open(p)
	if err != nil {
		done()
		if errors.Is(err, os.ErrNotExist) {
			return nil, providers.ErrNotFound
		}
		return nil, fmt.Errorf("sftp: open: %w", err)
	}
	return remoteFile{ReadCloser: f, done: done}, nil
}

func (s *SFTPStore) Size(ctx context.Context, name string) (int64, error) {
	p, err := s.remote(name)
	if err != nil {
		return 0, err
	}
	c, done, err := s.session(ctx)
	if err != nil {
		return 0, err
	}
	defer done()
	st, err := c.Stat(p)
	if errors.Is(err, os.ErrNotExist) {
		return 0, providers.ErrNotFound
	}
	if err != nil {
		return 0, fmt.Errorf("sftp: stat: %w", err)
	}
	return st.Size(), nil
}

func (s *SFTPStore) Delete(ctx context.Context, name string) error {
	p, err := s.remote(name)
	if err != nil {
		return err
	}
	c, done, err := s.session(ctx)
	if err != nil {
		return err
	}
	defer done()
	if err := c.Remove(p); err != nil && !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("sftp: delete: %w", err)
	}
	return nil
}

var _ Store = (*SFTPStore)(nil)
